    total = sum(sum(t) for t in years)
    return {"sub_jahr": sub, "einmal": einm, "puffer": puffer, "years": years, "total": total,
            "sub5": sum(t[0] for t in years), "einm5": einm + puffer, "betr5": sum(t[2] for t in years)}


